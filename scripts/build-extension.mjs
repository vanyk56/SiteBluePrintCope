#!/usr/bin/env node
// Generates the parts of the browser extension that are shared with the CLI, so both always run the same code:
//   extension/lib/inpage.js  ← src/inpage/{extract,snapshot,prepare,probes}.mjs   (window.__sbLib, MAIN world)
//   extension/lib/hooks.js   ← src/inpage/hooks.mjs                                  (document_start, MAIN world)
//   extension/lib/redact.js  ← src/capture/redact.mjs                                (service worker module)
// and keeps extension/manifest.json "version" equal to package.json. Run: npm run build:extension
// (--check: exit 1 when the generated files are out of date — used by the tests).
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = path.join(ROOT, 'extension');
const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8'));
const check = process.argv.includes('--check');
const HEAD = (src) => `/* GENERATED by scripts/build-extension.mjs from ${src} — do not edit by hand (npm run build:extension). */\n`;

const toUrl = (p) => pathToFileURL(p).href;
const extract = await import(toUrl(path.join(ROOT, 'src/inpage/extract.mjs')));
const snapshot = await import(toUrl(path.join(ROOT, 'src/inpage/snapshot.mjs')));
const prepare = await import(toUrl(path.join(ROOT, 'src/inpage/prepare.mjs')));
const probes = await import(toUrl(path.join(ROOT, 'src/inpage/probes.mjs')));
const hooks = await import(toUrl(path.join(ROOT, 'src/inpage/hooks.mjs')));

const fns = { ...pick(extract), ...pick(snapshot), ...pick(prepare), ...pick(probes) };
function pick(mod) { const o = {}; for (const [k, v] of Object.entries(mod)) if (typeof v === 'function') o[k] = v; return o; }
for (const [k, f] of Object.entries(fns)) {
  const src = f.toString();
  if (!/^(async\s+)?function\b/.test(src)) throw new Error(`${k}: only function declarations can be bundled`);
  if (/\bimport\s*\(|\brequire\s*\(/.test(src)) throw new Error(`${k}: in-page code must be self-contained`);
}
const inpage = HEAD('src/inpage/{extract,snapshot,prepare,probes}.mjs') + `(() => {
  'use strict';
  const VERSION = ${JSON.stringify(pkg.version)};
  if (window.__sbLib && window.__sbLib.version === VERSION) return;
${Object.entries(fns).map(([k, f]) => `  const ${k} = ${f.toString().replace(/\n/g, '\n  ')};`).join('\n')}
  Object.defineProperty(window, '__sbLib', { value: Object.freeze({ version: VERSION, ${Object.keys(fns).join(', ')} }), configurable: true, enumerable: false, writable: true });
})();
`;
const hooksJs = HEAD('src/inpage/hooks.mjs') + `(${hooks.installHooks.toString()})();\n`;
let redact = await fs.readFile(path.join(ROOT, 'src/capture/redact.mjs'), 'utf8');
if (/^\s*import\s/m.test(redact)) throw new Error('src/capture/redact.mjs must not import anything (it is copied into the extension)');
redact = HEAD('src/capture/redact.mjs') + redact;

const manifestFile = path.join(EXT, 'manifest.json');
const manifest = JSON.parse(await fs.readFile(manifestFile, 'utf8'));
manifest.version = pkg.version.replace(/[^0-9.]/g, '');
const manifestText = JSON.stringify(manifest, null, 2) + '\n';

const outputs = [
  [path.join(EXT, 'lib', 'inpage.js'), inpage],
  [path.join(EXT, 'lib', 'hooks.js'), hooksJs],
  [path.join(EXT, 'lib', 'redact.js'), redact],
  [manifestFile, manifestText],
];
let stale = 0;
for (const [file, text] of outputs) {
  const cur = await fs.readFile(file, 'utf8').catch(() => null);
  if (cur === text) continue;
  stale++;
  if (check) { console.error('устарел: ' + path.relative(ROOT, file)); continue; }
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text);
  console.log('записан: ' + path.relative(ROOT, file) + ` (${(text.length / 1024).toFixed(1)} KB)`);
}
if (check && stale) { console.error('Запусти: npm run build:extension'); process.exit(1); }
if (!stale) console.log('extension/lib актуален');
