// Self-healing build loop: `next build` → parse errors → deterministic fixers → LLM SEARCH/REPLACE patches → repeat.
// Deterministic fixes cover what generated code typically trips over (missing 'use client', custom elements in
// JSX, missing icon exports/imports, invalid DOM nesting, CSS that Lightning CSS rejects); everything else is sent
// to the configured LLM with the exact error and the file, and the answer is applied as minimal patches.
import path from 'node:path';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { log } from '../log.mjs';
import { ensureDir, exists, writeJSON } from '../util.mjs';

const IS_WIN = process.platform === 'win32';
const posix = (p) => p.split(path.sep).join('/');

// ---------- dependencies ----------
// next is resolvable from the project (own node_modules or any ancestor — Turbopack accepts an ancestor root with a lockfile)
export function findNext(projectRoot) {
  try { const req = createRequire(path.join(projectRoot, 'package.json')); const pkg = req.resolve('next/package.json'); return { pkg, bin: path.join(path.dirname(pkg), 'dist', 'bin', 'next'), root: path.dirname(path.dirname(path.dirname(pkg))) }; }
  catch { return null; }
}

export function run(cmd, args, { cwd, env = {}, timeoutMs = 600000, onData = null } = {}) {
  return new Promise((resolve) => {
    let out = ''; const t0 = Date.now();
    let child;
    try { child = spawn(cmd, args, { cwd, env: { ...process.env, ...env }, shell: IS_WIN && /^(npm|npx)(\.cmd)?$/.test(cmd), windowsHide: true }); }
    catch (e) { resolve({ code: -1, output: String(e.message || e), ms: 0 }); return; }
    const timer = setTimeout(() => { out += `\n[site-blueprint] таймаут ${Math.round(timeoutMs / 1000)} с — процесс остановлен\n`; try { child.kill('SIGKILL'); } catch {} }, timeoutMs);
    const take = (d) => { const s = d.toString(); out += s; if (out.length > 4e6) out = out.slice(-2e6); if (onData) onData(s); };
    child.stdout.on('data', take); child.stderr.on('data', take);
    child.on('error', (e) => { out += String(e.message || e); });
    child.on('close', (code) => { clearTimeout(timer); resolve({ code: code ?? -1, output: out, ms: Date.now() - t0 }); });
  });
}

// mode: shared (default) — one node_modules next to all results (<out>/..), installed once and reused;
//       local — npm install inside project/;  skip — never install (build only if next is already resolvable)
export async function ensureDeps(projectRoot, { mode = 'shared', outDir = path.dirname(projectRoot), timeoutMs = 900000 } = {}) {
  const found = findNext(projectRoot);
  if (found) return { ok: true, mode: 'found', location: found.root };
  if (mode === 'skip' || mode === false) return { ok: false, reason: 'зависимости не установлены (--deps skip) — выполни npm install в project/' };
  const pkg = JSON.parse(await fsp.readFile(path.join(projectRoot, 'package.json'), 'utf8'));
  const deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };
  const npm = IS_WIN ? 'npm.cmd' : 'npm';
  let dir = projectRoot;
  if (mode !== 'local') {
    dir = path.dirname(path.resolve(outDir)); // output/ — shared by every run
    const sharedPkg = path.join(dir, 'package.json');
    let cur = null; try { cur = JSON.parse(await fsp.readFile(sharedPkg, 'utf8')); } catch {}
    if (cur && cur.name !== 'site-blueprint-shared-deps') { log.warn(`${sharedPkg} уже существует и не принадлежит site-blueprint — ставлю зависимости локально в project/`); dir = projectRoot; }
    else {
      await writeJSON(sharedPkg, { name: 'site-blueprint-shared-deps', private: true, description: 'Shared node_modules for projects generated by site-blueprint (resolved from ./<run>/project).', dependencies: deps });
      // tests / offline machines: hard-link an existing node_modules instead of downloading
      const pre = process.env.SB_NEXT_MODULES;
      if (pre && fs.existsSync(path.join(pre, 'next')) && !fs.existsSync(path.join(dir, 'node_modules', 'next'))) {
        const r = IS_WIN ? { code: 1 } : await run('cp', ['-al', pre, path.join(dir, 'node_modules')], { timeoutMs: 300000 });
        if (r.code === 0) {
          const lock = path.join(path.dirname(pre), 'package-lock.json');
          if (fs.existsSync(lock) && !fs.existsSync(path.join(dir, 'package-lock.json'))) await fsp.copyFile(lock, path.join(dir, 'package-lock.json'));
          if (!fs.existsSync(path.join(dir, 'package-lock.json'))) await fsp.writeFile(path.join(dir, 'package-lock.json'), JSON.stringify({ name: 'site-blueprint-shared-deps', lockfileVersion: 3, requires: true, packages: {} }, null, 2));
          const again = findNext(projectRoot);
          if (again) return { ok: true, mode: 'linked', location: dir };
        }
      }
    }
  }
  log.info(`npm install (${dir === projectRoot ? 'в project/' : 'общие зависимости: ' + dir}) — первый раз это займёт 1–3 минуты…`);
  const r = await run(npm, ['install', '--no-audit', '--no-fund', '--loglevel=error'], { cwd: dir, timeoutMs });
  if (r.code !== 0) return { ok: false, reason: 'npm install завершился с ошибкой: ' + r.output.trim().split('\n').slice(-3).join(' ').slice(0, 300) };
  const again = findNext(projectRoot);
  return again ? { ok: true, mode: dir === projectRoot ? 'local' : 'shared', location: dir, ms: r.ms } : { ok: false, reason: 'после npm install next не найден' };
}

export async function nextBuild(projectRoot, { timeoutMs = 600000 } = {}) {
  const nx = findNext(projectRoot);
  if (!nx) return { code: -1, output: 'next не найден', ms: 0 };
  return run(process.execPath, [nx.bin, 'build'], { cwd: projectRoot, env: { NEXT_TELEMETRY_DISABLED: '1', NODE_ENV: 'production' }, timeoutMs });
}

// ---------- error parsing ----------
const LOC_RE = /(?:^|[\s(])(?:\.\/|\.\\)?((?:app|components|lib|mocks|types|src|pages)[\\/][^\s:()'"]+?\.(?:tsx?|jsx?|css|mjs))(?::(\d+)(?::(\d+))?)?/;
const strip = (s) => String(s).replace(/\x1b\[[0-9;]*m/g, '');

export function parseBuildErrors(output, projectRoot = '') {
  let text = strip(output);
  // Turbopack prints paths relative to its root (the shared deps folder) or absolute — make them project-relative
  if (projectRoot) {
    const abs = path.resolve(projectRoot);
    for (const p of [abs + path.sep, posix(abs) + '/', abs + '/', posix(abs) + path.sep]) text = text.split(p).join('./');
    const tail = posix(path.join(path.basename(path.dirname(abs)), path.basename(abs))) + '/';
    text = text.split('./' + tail).join('./').split(tail).join('./');
  }
  const lines = text.split(/\r?\n/);
  const errors = []; const seen = new Set();
  const push = (e) => { const k = `${e.file}|${e.line}|${e.message.slice(0, 120)}`; if (seen.has(k)) return; seen.add(k); errors.push(e); };
  for (let i = 0; i < lines.length; i++) {
    const m = LOC_RE.exec(lines[i]);
    if (!m) continue;
    // message: following lines until a blank line / next location (Turbopack prints a code frame in between)
    const body = [];
    for (let j = i + 1; j < Math.min(lines.length, i + 40); j++) {
      const l = lines[j];
      if (LOC_RE.test(l) && body.length) break;
      if (!l.trim() && body.some((x) => !/^\s*(\d+\s*\||>|\|)/.test(x))) break;
      body.push(l);
    }
    const msgLines = body.filter((l) => !/^\s*(>?\s*\d+\s*\||\|\s)/.test(l) && l.trim() && !/^\s*\^+\s*$/.test(l) && !/^\s*at\s/.test(l));
    const sameLine = lines[i].slice(lines[i].indexOf(m[1]) + m[0].trim().length).replace(/^[:\s]+/, '').trim();
    const message = ((sameLine && /[a-z]{3}/i.test(sameLine) ? sameLine.replace(/\s+at\s.*$/, '') + ' ' : '') + (msgLines.join(' ').replace(/\s+/g, ' ').trim() || lines[i].trim())).slice(0, 600);
    if (/^(Import trace|Compiled|Creating|Collecting|Generating|Route|○|ƒ|├|└|┌)/.test(message)) continue;
    if (!/error|failed|cannot|can't|unexpected|expected|not assignable|does not exist|missing|invalid|unknown|warning|not found|duplicate|no exported member/i.test(message + lines[i])) continue;
    push({ file: posix(m[1]), line: m[2] ? +m[2] : null, col: m[3] ? +m[3] : null, message, kind: kindOf(message, m[1]) });
  }
  // errors without a file location
  for (const l of lines) {
    if (/You're importing a component that needs `?(useState|useEffect|useRef|useReducer|useContext|createContext)/.test(l)) push({ file: null, line: null, col: null, message: l.trim(), kind: 'client' });
    if (/Event handlers cannot be passed to Client Component props/.test(l)) push({ file: null, line: null, col: null, message: l.trim(), kind: 'client' });
    if (/Unexpected token (BadUrl|Function|Delim)|while optimizing generated CSS/.test(l)) push({ file: null, line: null, col: null, message: l.trim().slice(0, 600), kind: 'css' });
    const pre = /Error occurred prerendering page "([^"]+)"/.exec(l);
    if (pre) push({ file: null, line: null, col: null, message: l.trim(), kind: 'prerender', route: pre[1] });
  }
  return errors;
}

function kindOf(msg, file) {
  if (/\.css$/.test(file) || /css|tailwind/i.test(msg)) return 'css';
  if (/IntrinsicElements/.test(msg)) return 'custom-element';
  if (/has no exported member|Cannot find name|Module not found|Can't resolve|Cannot find module/i.test(msg)) return 'import';
  if (/use client|useState|useEffect|Event handlers cannot/i.test(msg)) return 'client';
  if (/cannot be a (child|descendant)|In HTML, .* cannot|validateDOMNesting|hydration/i.test(msg)) return 'nesting';
  if (/Parsing|Expected|Unexpected|Unterminated|JSX/i.test(msg)) return 'syntax';
  if (/Type error|not assignable|does not exist on type/i.test(msg)) return 'type';
  return 'other';
}

// ---------- deterministic fixers ----------
async function readRel(root, rel) { try { return await fsp.readFile(path.join(root, rel), 'utf8'); } catch { return null; } }
async function listFiles(root, re = /\.(tsx?|css)$/) {
  const out = [];
  const walk = async (d, rel = '') => {
    for (const e of await fsp.readdir(d, { withFileTypes: true }).catch(() => [])) {
      if (e.name === 'node_modules' || e.name === '.next' || e.name.startsWith('.sb-')) continue;
      const r = rel ? rel + '/' + e.name : e.name;
      if (e.isDirectory()) await walk(path.join(d, e.name), r); else if (re.test(e.name)) out.push(r);
    }
  };
  await walk(root);
  return out;
}
const HOOK_RE = /\b(useState|useEffect|useRef|useReducer|useContext|useMemo|useCallback|useLayoutEffect|useId|createContext)\s*[(<]/;
const HANDLER_RE = /\son(Click|Change|Submit|Input|KeyDown|KeyUp|MouseEnter|MouseLeave|Focus|Blur|Toggle|PointerDown)=\{/;
const hasDirective = (t) => /^\s*(\/\/[^\n]*\n|\/\*[\s\S]*?\*\/\s*)*['"]use client['"]/.test(t);

export const FIXERS = [
  {
    // hooks / event handlers in a file without 'use client'
    id: 'use-client', match: (e) => e.kind === 'client' || /useState|useEffect|Event handlers cannot|use client/i.test(e.message),
    async apply(root, errs, ctx) {
      const files = new Set(errs.map((e) => e.file).filter(Boolean));
      for (const f of await listFiles(root, /\.tsx$/)) if (!f.startsWith('app/') || !/\/(page|layout)\.tsx$/.test(f)) files.add(f);
      const changed = [];
      for (const f of files) {
        const t = await readRel(root, f); if (t == null || hasDirective(t)) continue;
        if (!HOOK_RE.test(t) && !HANDLER_RE.test(t)) continue;
        if (/^export const metadata|generateMetadata/m.test(t)) continue; // never turn a page with metadata into a client file
        await ctx.write(f, "'use client';\n\n" + t); changed.push(f);
      }
      return changed;
    },
  },
  {
    // <nb-badge> & co: declare unknown custom elements for TypeScript
    id: 'custom-elements', match: (e) => e.kind === 'custom-element',
    async apply(root, errs, ctx) {
      const tags = new Set();
      for (const e of errs) for (const m of e.message.matchAll(/Property '([a-z][\w-]*-[\w-]*)' does not exist on type 'JSX\.IntrinsicElements'/g)) tags.add(m[1]);
      if (!tags.size) for (const f of await listFiles(root, /\.tsx$/)) { const t = await readRel(root, f); for (const m of (t || '').matchAll(/<([a-z][a-z0-9]*-[a-z0-9-]+)[\s>/]/g)) tags.add(m[1]); }
      if (!tags.size) return [];
      const file = 'types/custom-elements.d.ts';
      const cur = (await readRel(root, file)) || '';
      const known = new Set([...cur.matchAll(/'([a-z][\w-]*-[\w-]*)':/g)].map((m) => m[1]));
      const all = [...new Set([...known, ...tags])].sort();
      if (all.length === known.size) return [];
      await ctx.write(file, [
        '// Custom elements (Web Components) of the original site. Their shadow DOM is in snapshots/*.html;',
        '// replace them with React components or register the element definitions.',
        "import type { DetailedHTMLProps, HTMLAttributes } from 'react';", '',
        "declare module 'react' {", '  namespace JSX {', '    interface IntrinsicElements {',
        ...all.map((t) => `      '${t}': DetailedHTMLProps<HTMLAttributes<HTMLElement>, HTMLElement> & Record<string, unknown>;`),
        '    }', '  }', '}', '',
      ].join('\n'));
      return [file];
    },
  },
  {
    // `X` is not exported by components/icons → stub; `Cannot find name 'X'` → add the import if X exists somewhere
    id: 'imports', match: (e) => e.kind === 'import',
    async apply(root, errs, ctx) {
      const changed = [];
      const icons = await readRel(root, 'components/icons.tsx');
      for (const e of errs) {
        let m = /has no exported member(?: named)? '(\w+)'/.exec(e.message);
        if (m && icons != null && /icons/.test(e.message) && !new RegExp(`export function ${m[1]}\\b`).test(icons)) {
          const cur = await readRel(root, 'components/icons.tsx');
          await ctx.write('components/icons.tsx', cur + `\n// stub added by site-blueprint heal: the original icon was not captured\nexport function ${m[1]}(props: IconProps) {\n  return <svg viewBox="0 0 24 24" width={24} height={24} fill="none" stroke="currentColor" aria-hidden="true" {...props}><circle cx="12" cy="12" r="9" /></svg>;\n}\n`);
          changed.push('components/icons.tsx'); continue;
        }
        m = /Cannot find name '([A-Z]\w+)'/.exec(e.message);
        if (m && e.file) {
          const name = m[1];
          for (const f of await listFiles(root, /\.tsx?$/)) {
            if (f === e.file) continue;
            const t = await readRel(root, f);
            if (t && new RegExp(`export (function|const) ${name}\\b`).test(t)) {
              const src = await readRel(root, e.file); if (src == null || src.includes(`{ ${name} }`)) break;
              const imp = `import { ${name} } from '@/${f.replace(/\.tsx?$/, '')}';\n`;
              const at = hasDirective(src) ? src.indexOf('\n', src.search(/['"]use client['"]/)) + 1 : 0;
              await ctx.write(e.file, src.slice(0, at) + imp + src.slice(at)); changed.push(e.file); break;
            }
          }
        }
      }
      return changed;
    },
  },
  {
    // invalid DOM nesting from the source HTML: <p><div>, <a><a>, <button><button> (hydration errors / React warnings)
    id: 'nesting', match: (e) => e.kind === 'nesting' || e.kind === 'syntax',
    async apply(root, errs, ctx) {
      const { fixNesting } = await import('../analyze/jsxfix.mjs');
      const files = new Set(errs.map((e) => e.file).filter((f) => f && f.endsWith('.tsx')));
      const changed = [];
      for (const f of files) { const t = await readRel(root, f); if (t == null) continue; const n = fixNesting(t); if (n !== t) { await ctx.write(f, n); changed.push(f); } }
      return changed;
    },
  },
  {
    // aria-selected={item.x} where x is the string "true"/"false" → boolean expression (TS: Booleanish)
    id: 'aria-bool', match: (e) => /Types of property '"(aria-[a-z]+)"' are incompatible/.test(e.message) && /Booleanish|boolean/.test(e.message),
    async apply(root, errs, ctx) {
      const changed = new Set();
      for (const e of errs) {
        const attr = /Types of property '"(aria-[a-z]+)"'/.exec(e.message)[1];
        const t = await readRel(root, e.file); if (t == null) continue;
        const n = t.replace(new RegExp(`${attr}=\\{([\\w.]+)\\}`, 'g'), (m, x) => `${attr}={String(${x}) === 'true'}`);
        if (n !== t) { await ctx.write(e.file, n); changed.add(e.file); }
      }
      return [...changed];
    },
  },
  {
    // syntax error at a known line of a CSS file: re-normalise url()s of a custom property, otherwise comment the line out
    id: 'css-line', match: (e) => e.kind === 'css' && e.file && /\.css$/.test(e.file) && e.line,
    async apply(root, errs, ctx) {
      const { normalizeUrls } = await import('../analyze/cssvars.mjs');
      const changed = new Set();
      for (const e of errs) {
        const t = await readRel(root, e.file); if (t == null) continue;
        const lines = t.split('\n'); const i = e.line - 1; if (!lines[i]) continue;
        const l = lines[i];
        const m = /^(\s*--[\w-]+\s*:\s*)(.*?);?\s*$/.exec(l);
        let fixed = m ? m[1] + normalizeUrls(m[2]) + ';' : null;
        if (!fixed || fixed === l) fixed = `/* site-blueprint heal: invalid line removed — ${l.trim().replace(/\*\//g, '* /').slice(0, 200)} */`;
        lines[i] = fixed; await ctx.write(e.file, lines.join('\n')); changed.add(e.file);
      }
      return [...changed];
    },
  },
  {
    // classes with raw url(data:…)/quotes/spaces that Lightning CSS rejects (BadUrl) → CSS variables in @theme
    id: 'css-vars', match: (e) => e.kind === 'css',
    async apply(root, errs, ctx) {
      const { sanitizeProjectClasses } = await import('../analyze/cssvars.mjs');
      return sanitizeProjectClasses(root, ctx);
    },
  },
];

// ---------- LLM patches ----------
export function parsePatches(text) {
  const out = [];
  const re = /(?:^|\n)(?:FILE|File|ФАЙЛ):\s*`?([^\n`]+?)`?\s*\n(?:```[\w-]*\n)?<{5,9} SEARCH\n([\s\S]*?)\n={5,9}\n([\s\S]*?)\n>{5,9} REPLACE/g;
  for (const m of String(text || '').matchAll(re)) out.push({ file: m[1].trim().replace(/^\.?\//, ''), search: m[2], replace: m[3] });
  return out;
}
export function applyPatch(src, { search, replace }) {
  if (!search || !String(search).trim()) return null; // an empty/whitespace SEARCH would match anywhere
  if (src.includes(search)) return src.replace(search, () => replace);
  // tolerant match: same lines ignoring indentation / trailing spaces
  const norm = (s) => s.split('\n').map((l) => l.trim()).join('\n');
  const lines = src.split('\n'); const want = norm(search).split('\n'); const n = want.length;
  if (!n || !want.join('').trim()) return null;
  for (let i = 0; i + n <= lines.length; i++) {
    if (lines.slice(i, i + n).map((l) => l.trim()).join('\n') === want.join('\n')) {
      const indent = (lines[i].match(/^\s*/) || [''])[0];
      const rep = replace.split('\n').map((l, k) => (k === 0 || !l.trim() ? l : l)).map((l) => (l.trim() && !/^\s/.test(l) ? indent + l : l));
      return [...lines.slice(0, i), ...rep, ...lines.slice(i + n)].join('\n');
    }
  }
  return null;
}

async function llmFix(root, errs, ctx) {
  if (!ctx.llm) return [];
  const { chat } = await import('../llm/client.mjs');
  const { FIX_SYSTEM, fixPrompt } = await import('../llm/prompts.mjs');
  const byFile = new Map();
  for (const e of errs) if (e.file && !byFile.has(e.file)) byFile.set(e.file, []);
  for (const e of errs) if (e.file) byFile.get(e.file).push(e);
  const targets = [...byFile.keys()].slice(0, 3);
  if (!targets.length) {
    // no location (prerender errors…): send the pages mentioned or the layout
    const routes = errs.map((e) => e.route).filter(Boolean);
    for (const r of routes) targets.push(r === '/' ? 'app/page.tsx' : `app${r}/page.tsx`);
    if (!targets.length) return [];
  }
  const files = [];
  for (const f of targets) { const t = await readRel(root, f); if (t != null) files.push({ file: f, text: t.length > 60000 ? t.slice(0, 60000) : t, errors: byFile.get(f) || errs.filter((e) => !e.file) }); }
  if (!files.length) return [];
  let res;
  try { res = await chat(ctx.llm, [{ role: 'system', content: FIX_SYSTEM }, { role: 'user', content: fixPrompt({ files, output: ctx.lastOutput }) }], { maxTokens: 8000, temperature: 0.1, label: 'heal' }); }
  catch (e) { log.warn('LLM-исправление: ' + String((e && e.message) || e).split('\n')[0]); return []; }
  const patches = parsePatches(res.text);
  const changed = [];
  for (const p of patches) {
    if (p.file.includes('..') || path.isAbsolute(p.file)) continue;
    const cur = await readRel(root, p.file); if (cur == null) continue;
    const next = applyPatch(cur, p);
    if (next != null && next !== cur) { await ctx.write(p.file, next); changed.push(p.file); }
  }
  ctx.llmCalls = (ctx.llmCalls || 0) + 1;
  return [...new Set(changed)];
}

/**
 * @param {string} root  project directory
 * @param {object} o     { iterations, llm (resolved LLM config or null), build: async () => ({ code, output }), outDir }
 */
export async function healProject(root, { iterations = 4, llm = null, build = null, outDir = path.dirname(root), onIteration = null } = {}) {
  const doBuild = build || (() => nextBuild(root));
  const backupDir = path.join(outDir, 'verify', 'heal-backup');
  const history = [];
  const ctx = {
    llm, llmCalls: 0, lastOutput: '',
    async write(rel, text) {
      const abs = path.join(root, rel);
      const prev = await fsp.readFile(abs, 'utf8').catch(() => null);
      // verify/heal-backup/<iteration>/<file>: the version before the first change made in that iteration
      const b = path.join(backupDir, String(Math.max(1, history.length)), rel);
      if (prev != null && !fs.existsSync(b)) { await ensureDir(path.dirname(b)); await fsp.writeFile(b, prev).catch(() => {}); }
      await ensureDir(path.dirname(abs)); await fsp.writeFile(abs, text);
    },
  };
  let ok = false; let last = null;
  const max = Math.max(1, iterations | 0);
  for (let i = 1; i <= max + 1; i++) {
    const r = await doBuild();
    last = r; ctx.lastOutput = strip(r.output).slice(-6000);
    const errors = parseBuildErrors(r.output, root);
    const passed = r.code === 0;
    const cssWarn = passed && errors.some((e) => e.kind === 'css');
    const step = { iteration: i, ok: passed, ms: r.ms, errors: errors.slice(0, 30), fixes: [] };
    history.push(step);
    if (onIteration) onIteration(step);
    if (passed && !cssWarn) { ok = true; break; }
    if (i > max) { ok = passed; break; }
    // deterministic fixers first
    const relevant = passed ? errors.filter((e) => e.kind === 'css') : errors;
    for (const f of FIXERS) {
      const mine = relevant.filter(f.match);
      if (!mine.length) continue;
      try { const ch = await f.apply(root, mine, ctx); if (ch.length) step.fixes.push({ by: f.id, files: ch }); }
      catch (e) { step.fixes.push({ by: f.id, error: String((e && e.message) || e).slice(0, 200) }); }
    }
    if (passed && !step.fixes.some((x) => x.files)) { ok = true; break; } // only cosmetic CSS warnings left
    if (!step.fixes.some((x) => x.files) && !passed) {
      const ch = await llmFix(root, relevant.length ? relevant : [{ file: null, message: ctx.lastOutput.slice(-1500), kind: 'other' }], ctx);
      if (ch.length) step.fixes.push({ by: 'llm', files: ch });
    }
    if (!step.fixes.some((x) => x.files)) { ok = passed; break; } // no progress possible
  }
  const result = { ok, iterations: history.length, history, llmCalls: ctx.llmCalls, tail: strip(last ? last.output : '').split('\n').slice(-40).join('\n') };
  await writeJSON(path.join(outDir, 'verify', 'heal.json'), result).catch(() => {});
  return result;
}
